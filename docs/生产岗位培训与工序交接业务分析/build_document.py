def table(headers,rows,widths=None):
    t=doc.add_table(rows=1,cols=len(headers));t.alignment=WD_TABLE_ALIGNMENT.CENTER;t.autofit=False
    if widths is None:widths=[WIDTH/len(headers)]*len(headers)
    for c,w in zip(t.columns,widths):c.width=Inches(w)
    pr=t._tbl.tblPr
    borders=OxmlElement('w:tblBorders')
    for edge in ['top','left','bottom','right','insideH','insideV']:
        e=OxmlElement('w:'+edge);e.set(qn('w:val'),'single');e.set(qn('w:sz'),'4');e.set(qn('w:color'),'D9D9D9');borders.append(e)
    pr.append(borders)
    margin=OxmlElement('w:tblCellMar')
    for side,n in [('top',80),('bottom',80),('left',100),('right',100)]:
        e=OxmlElement('w:'+side);e.set(qn('w:w'),str(n));e.set(qn('w:type'),'dxa');margin.append(e)
    pr.append(margin)
    for i,val in enumerate(headers):t.rows[0].cells[i].text=val
    repeat=OxmlElement('w:tblHeader');t.rows[0]._tr.get_or_add_trPr().append(repeat)
    for row in rows:
        cells=t.add_row().cells
        for c,txt in zip(cells,row):c.text=str(txt)
    for ri,row in enumerate(t.rows):
        no_split=OxmlElement('w:cantSplit');row._tr.get_or_add_trPr().append(no_split)
        for ci,cell in enumerate(row.cells):
            cell.width=Inches(widths[ci]);cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if ri==0:
                shade=OxmlElement('w:shd');shade.set(qn('w:fill'),'DFEAF2');cell._tc.get_or_add_tcPr().append(shade)
            for par in cell.paragraphs:
                par.paragraph_format.space_after=Pt(2);par.paragraph_format.space_before=Pt(2);par.paragraph_format.line_spacing=Pt(14)
                if ci==0 and widths[ci]<1.1:par.alignment=WD_ALIGN_PARAGRAPH.CENTER
                for r in par.runs:r.font.size=Pt(10);r.font.bold=(ri==0)
    p('').paragraph_format.space_after=Pt(0)
    return t

